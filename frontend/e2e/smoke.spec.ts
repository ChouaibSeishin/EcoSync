import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
test('real login, protected access, empty states, status and logout', async ({ page, request }) => {
  const username = process.env.E2E_USERNAME;
  const password = process.env.E2E_PASSWORD;
  if (!username || !password) throw new Error('E2E_USERNAME and E2E_PASSWORD are required; use unique local fixture credentials.');
  expect((await request.get('/api/session')).status()).toBe(401);
  expect((await request.post('/api/auth/login', { form: { username, password } })).status()).toBe(403);
  await page.goto('/');
  await page.request.get('/api/csrf');
  const anonymousCookie = (await page.context().cookies()).find(c => c.name === 'ECOSYNC_SESSION');
  await page.getByLabel('Username').fill(username);
  await page.getByLabel('Password').fill(password);
  await page.getByRole('button', { name: 'Sign in to workspace' }).click();
  await expect(page.getByRole('heading', { name: 'A clearer view starts here.' })).toBeVisible();
  await page.getByRole('button', { name: /Explore what/ }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).toBeHidden();
  await page.getByRole('link', { name: 'Integrations', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'No integrations yet' })).toBeVisible();
  await page.getByRole('link', { name: /AI workspace/ }).click();
  await expect(page.getByRole('heading', { name: 'Good answers start with trusted sources.' })).toBeVisible();
  await page.getByRole('link', { name: 'System status', exact: true }).click();
  await expect(page.getByText('Core services are available')).toBeVisible();
  const cookie = (await page.context().cookies()).find(c => c.name === 'ECOSYNC_SESSION');
  expect(cookie?.value).not.toBe(anonymousCookie?.value);
  expect(cookie?.httpOnly).toBe(true); expect(cookie?.sameSite).toBe('Strict');
  await page.setViewportSize({ width: 390, height: 844 });
  const menu = page.getByRole('button', { name: 'Open navigation' });
  await menu.click();
  await expect(menu).toHaveAttribute('aria-expanded', 'true');
  await page.keyboard.press('Escape');
  await expect(menu).toHaveAttribute('aria-expanded', 'false');
  await expect(page.locator('#workspace-navigation')).toBeHidden();
  await menu.click();
  await page.getByRole('link', { name: 'Overview', exact: true }).click();
  await expect(page.locator('#workspace-navigation')).toBeHidden();
  await expect(page.getByRole('heading', { name: 'A clearer view starts here.' })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await mkdir('../.verification/phase1', { recursive: true });
  await page.screenshot({ path: '../.verification/phase1/dashboard-mobile.png', fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: '../.verification/phase1/dashboard-desktop.png', fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: 'Sign out' }).click();
  await expect(page.getByLabel('Username')).toBeVisible();
  expect((await page.request.get('/api/session')).status()).toBe(401);
  if (cookie) {
    const stale = await request.get('/api/session', { headers: { Cookie: 'ECOSYNC_SESSION=' + cookie.value } });
    expect(stale.status()).toBe(401);
  }
});
